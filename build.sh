#!/usr/bin/env bash
# Builds site/*.html from src/pages/*.html and the shared partials.
# Usage: bash build.sh   (Git Bash on Windows, or any bash 4+)
#
# Each page in src/pages starts with a metadata block:
#   <!--
#   title: Page title
#   description: Meta description
#   nav: shop          (key of the menu link to highlight)
#   group: shop        (key of the dropdown that contains it, optional)
#   -->
set -euo pipefail
shopt -u patsub_replacement 2>/dev/null || true
cd "$(dirname "$0")"
source src/config.sh

head_html=$(<src/partials/head.html)
header_html=$(<src/partials/header.html)
footer_html=$(<src/partials/footer.html)

meta() { sed -n "s/^$1: //p" "$2" | head -1; }

count=0
for page in src/pages/*.html; do
  name=$(basename "$page")
  title=$(meta title "$page")
  desc=$(meta description "$page")
  nav=$(meta nav "$page")
  group=$(meta group "$page")
  robots=$(meta robots "$page"); robots=${robots:-index, follow}
  [[ ${PREVIEW_NOINDEX:-false} == true ]] && robots="noindex, nofollow"
  body=$(sed '1,/^-->$/d' "$page")

  canonical="$SITE_URL$name"
  [[ $name == index.html ]] && canonical="$SITE_URL"

  out="$head_html
$header_html
$body
$footer_html"

  out=${out//'{{TITLE}}'/"$title"}
  out=${out//'{{DESCRIPTION}}'/"$desc"}
  out=${out//'{{ROBOTS}}'/"$robots"}
  out=${out//'{{CANONICAL}}'/"$canonical"}
  out=${out//'{{SITE_URL}}'/"$SITE_URL"}
  out=${out//'{{SHOPIFY_URL}}'/"$SHOPIFY_URL"}
  out=${out//'{{EBAY_URL}}'/"$EBAY_URL"}
  out=${out//'{{PHONE}}'/"$PHONE"}
  out=${out//'{{PHONE_TEL}}'/"$PHONE_TEL"}
  out=${out//'{{EMAIL}}'/"$EMAIL"}
  out=${out//'{{ADDRESS}}'/"$ADDRESS"}
  out=${out//'{{COMPANY_NO}}'/"$COMPANY_NO"}
  out=${out//'{{VAT_NO}}'/"$VAT_NO"}
  out=${out//'{{YEAR}}'/"$(date +%Y)"}
  [[ -n $nav ]] && out=${out//"{{nav:$nav}}"/' aria-current="page"'}
  [[ -n $group ]] && out=${out//"{{group:$group}}"/' data-current'}
  out=$(sed -E 's/\{\{(nav|group):[a-z-]+\}\}//g' <<<"$out")

  printf '%s\n' "$out" > "site/$name"
  count=$((count + 1))
done

cat > site/js/config.js <<EOF
// Generated by build.sh from src/config.sh. Do not edit by hand.
window.SLAV_CONFIG = { shopifyUrl: "$SHOPIFY_URL", ebayUrl: "$EBAY_URL" };
EOF

echo "Built $count pages into site/"
